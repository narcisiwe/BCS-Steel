const langSelect = document.getElementById('langSelect');
const themeToggle = document.getElementById('themeToggle');
const year = document.getElementById('year');
const heroMedia = document.querySelector('.hero-media');
const slideButtons = [...document.querySelectorAll('.slide-numbers button')];
let currentLang = 'lv';
let currentSlide = 0;
let slideTimer;

year.textContent = new Date().getFullYear();

function setHeroSlide(index, resetTimer = true) {
  currentSlide = (index + 4) % 4;
  const slide = heroSlides[currentLang][currentSlide];
  document.querySelector('[data-i18n="hero_eyebrow"]').textContent = slide.eyebrow;
  document.querySelector('[data-i18n="hero_title_1"]').textContent = slide.title1;
  document.querySelector('[data-i18n="hero_title_2"]').textContent = slide.title2;
  document.querySelector('[data-i18n="hero_text"]').textContent = slide.text;

  heroMedia.classList.add('is-changing');
  window.setTimeout(() => {
    heroMedia.style.backgroundImage = `url('${slide.image}')`;
    heroMedia.classList.remove('is-changing');
  }, 140);

  slideButtons.forEach((btn, i) => btn.classList.toggle('is-active', i === currentSlide));
  if (resetTimer) restartSlider();
}

function restartSlider() {
  clearInterval(slideTimer);
  slideTimer = setInterval(() => setHeroSlide(currentSlide + 1, false), 6000);
}

function setLanguage(lang) {
  document.body.classList.add('is-switching');
  currentLang = translations[lang] ? lang : 'lv';
  const dict = translations[currentLang];
  document.documentElement.lang = currentLang;
  langSelect.value = currentLang;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key] && !key.startsWith('hero_')) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key]) el.placeholder = dict[key];
  });

  setHeroSlide(currentSlide, false);
  localStorage.setItem('bcsSteelLangV4', currentLang);
  setTimeout(() => document.body.classList.remove('is-switching'), 120);
}

function setTheme(theme) {
  document.documentElement.dataset.theme = theme;
  localStorage.setItem('bcsSteelThemeV4', theme);
}

slideButtons.forEach(btn => btn.addEventListener('click', () => setHeroSlide(Number(btn.dataset.slide))));
langSelect.addEventListener('change', e => setLanguage(e.target.value));
themeToggle.addEventListener('click', () => setTheme(document.documentElement.dataset.theme === 'dark' ? 'light' : 'dark'));

setTheme(localStorage.getItem('bcsSteelThemeV4') || 'dark');
setLanguage('lv');
restartSlider();
