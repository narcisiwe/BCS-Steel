// Reserve the tallest slide title for this language/width so autoplay does not
// shift the following sections. No title or image is stretched or truncated.
function reserveTitleSpace() {
  const title = document.querySelector('.hero h1');
  const probe = title.cloneNode(true);
  probe.removeAttribute('id');
  probe.setAttribute('aria-hidden', 'true');
  probe.style.cssText = `position:absolute;visibility:hidden;pointer-events:none;width:${title.getBoundingClientRect().width}px;min-height:0;height:auto;`;
  probe.querySelectorAll('[data-i18n]').forEach(node => node.removeAttribute('data-i18n'));
  title.parentElement.append(probe);
  let height = 0;
  slides.forEach(slide => {
    probe.children[0].textContent = slide.title1[currentLanguage];
    probe.children[1].textContent = slide.title2[currentLanguage];
    height = Math.max(height, probe.getBoundingClientRect().height);
  });
  probe.remove();
  title.style.minHeight = `${Math.ceil(height)}px`;
}
let titleWidth = 0;
if ('ResizeObserver' in window) new ResizeObserver(([entry]) => {
  if (Math.abs(entry.contentRect.width - titleWidth) < 1) return;
  titleWidth = entry.contentRect.width;
  reserveTitleSpace();
}).observe(document.querySelector('.hero-content'));
document.fonts?.ready.then(reserveTitleSpace);
