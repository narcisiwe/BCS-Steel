const languageSelect = document.getElementById('languageSelect');
const hero = document.getElementById('home');
const heroBg = document.getElementById('heroBg');
const slideButtons = document.querySelectorAll('.slide-dot');
const menuBtn = document.getElementById('menuBtn');

let currentLanguage = 'lv';
let currentSlide = 0;
let autoSlideTimer;

function applyTranslations(language) {
  currentLanguage = language;
  document.documentElement.lang = language;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    const value = translations[language]?.[key];

    if (value) {
      element.textContent = value;
    }
  });

  applySlide(currentSlide, false);
}

function applySlide(index, animate = true) {
  currentSlide = index;
  const slide = slides[index];

  hero.dataset.slide = String(index);

  if (animate) {
    heroBg.classList.add('is-changing');
  }

  window.setTimeout(() => {
    heroBg.style.backgroundImage = `url('${slide.image}')`;

    const title1 = document.querySelector('[data-i18n="heroTitle1"]');
    const title2 = document.querySelector('[data-i18n="heroTitle2"]');

    title1.textContent = slide.title1[currentLanguage];
    title2.textContent = slide.title2[currentLanguage];

    slideButtons.forEach((button) => {
      const isActive = Number(button.dataset.slide) === index;
      button.classList.toggle('active', isActive);
    });

    heroBg.classList.remove('is-changing');
  }, animate ? 160 : 0);
}

function startAutoSlide() {
  window.clearInterval(autoSlideTimer);

  autoSlideTimer = window.setInterval(() => {
    const nextSlide = (currentSlide + 1) % slides.length;
    applySlide(nextSlide);
  }, 6000);
}

function closeMobileMenu() {
  document.body.classList.remove('nav-open');
}

languageSelect.addEventListener('change', (event) => {
  applyTranslations(event.target.value);
});

slideButtons.forEach((button) => {
  button.addEventListener('click', () => {
    applySlide(Number(button.dataset.slide));
    startAutoSlide();
  });
});

menuBtn.addEventListener('click', () => {
  document.body.classList.toggle('nav-open');
});

document.querySelectorAll('.main-nav a').forEach((link) => {
  link.addEventListener('click', closeMobileMenu);
});

applyTranslations('lv');
startAutoSlide();
