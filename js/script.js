function updateMenu(open, restoreFocus = false) {
  document.body.classList.toggle('nav-open', open);
  menuBtn.setAttribute('aria-expanded', String(open));
  menuBtn.setAttribute('aria-label', t(open ? 'closeMenu' : 'openMenu'));
  if (restoreFocus) menuBtn.focus();
}

function applyTranslations(language) {
  if (!Object.hasOwn(translations, language)) language = 'lv';
  currentLanguage = language;
  document.documentElement.lang = language;
  languageSelect.value = language;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = translations[language][element.dataset.i18n];
    if (value) element.textContent = value;
  });
  ['placeholder', 'alt', 'aria-label'].forEach((attribute) => {
    document.querySelectorAll(`[data-i18n-${attribute}]`).forEach((element) => {
      const value = element.getAttribute(`data-i18n-${attribute}`);
      if (translations[language][value]) element.setAttribute(attribute, t(value));
    });
  });
  document.title = t('metaTitle');
  document.querySelector('meta[name="description"]').content = t('metaDescription');
  document.querySelector('meta[property="og:title"]').content = t('metaTitle');
  document.querySelector('meta[property="og:description"]').content = t('metaDescription');
  const canonical = new URL(language === 'lv' ? './' : `${language}/`, 'https://narcisiwe.github.io/BCS-Steel/').href;
  document.querySelector('link[rel="canonical"]').href = canonical;
  document.querySelector('meta[property="og:url"]').content = canonical;
  updateMenu(document.body.classList.contains('nav-open'));
  refreshFormLabels();
  if (statusKey) formStatus.textContent = t(statusKey);
  validateFile();
  applySlide(currentSlide, false);
  reserveTitleSpace();
  updatePlayback();
}

function applySlide(index, animate = true) {
  if (!slides[index]) return;
  window.clearTimeout(slideChangeTimer);
  currentSlide = index;
  const slide = slides[index];
  hero.dataset.slide = String(index);
  const change = () => {
    heroBg.style.backgroundImage = `url("${new URL(slide.image, siteRoot).href}")`;
    document.querySelector('[data-i18n="heroTitle1"]').textContent = slide.title1[currentLanguage];
    document.querySelector('[data-i18n="heroTitle2"]').textContent = slide.title2[currentLanguage];
    slideButtons.forEach((button, n) => {
      const active = n === index;
      button.classList.toggle('active', active);
      button.setAttribute('aria-current', String(active));
      button.setAttribute('aria-label', `${n + 1}: ${slides[n].title1[currentLanguage]}`);
    });
    heroBg.classList.remove('is-changing');
    hero.dispatchEvent(new CustomEvent('bcs:slidechange', { detail: { animate, index } }));
  };
  if (animate && !reducedMotion.matches) {
    heroBg.classList.add('is-changing');
    slideChangeTimer = window.setTimeout(change, 160);
  } else change();
}

