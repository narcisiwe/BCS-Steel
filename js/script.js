function refreshFormLabels() {
  form.querySelector('button[type="submit"] span').textContent = t(submitting ? 'sending' : formEndpoint ? 'formSubmit' : 'mailSubmit');
  document.getElementById('formNotice').hidden = Boolean(formEndpoint);
}
function validateFile() {
  const input = form.elements.drawing;
  const file = input.files[0];
  const valid = !file || (file.size <= 10 * 1024 * 1024 && /\.(dxf|dwg|pdf|step|stp|jpe?g|png)$/i.test(file.name));
  input.setCustomValidity(valid ? '' : t('fileError'));
  return valid;
}
form.elements.drawing.addEventListener('change', validateFile);
form.addEventListener('submit', async (event) => {
  event.preventDefault();
  if (submitting || !validateFile() || !form.reportValidity()) return;
  if (!formEndpoint) {
    const data = new FormData(form);
    const body = ['name', 'company', 'email', 'phone', 'service', 'message'].map(key => `${key}: ${data.get(key) || ''}`).join('\n');
    statusKey = 'mailPrepared';
    formStatus.textContent = t(statusKey);
    window.location.href = `mailto:info@bcssteel.lv?subject=${encodeURIComponent('BCS Steel enquiry')}&body=${encodeURIComponent(body)}`;
    return;
  }
  submitting = true;
  const submitButton = form.querySelector('button[type="submit"]');
  submitButton.disabled = true;
  form.setAttribute('aria-busy', 'true');
  refreshFormLabels();
  const controller = new AbortController();
  const timeout = window.setTimeout(() => controller.abort(), 20000);
  try {
    const endpoint = new URL(formEndpoint);
    if (endpoint.protocol !== 'https:') throw new Error('HTTPS endpoint required');
    const data = new FormData(form);
    data.set('language', currentLanguage);
    const response = await fetch(endpoint, { method: 'POST', body: data, signal: controller.signal, headers: { Accept: 'application/json' } });
    if (!response.ok) throw new Error('Submission rejected');
    // This reports server acceptance only, never claims mailbox delivery.
    statusKey = 'sent';
    form.reset();
  } catch {
    statusKey = 'sendError';
  } finally {
    window.clearTimeout(timeout);
    submitting = false;
    submitButton.disabled = false;
    form.removeAttribute('aria-busy');
    refreshFormLabels();
    formStatus.textContent = t(statusKey);
    formStatus.focus({ preventScroll: true });
  }
});

